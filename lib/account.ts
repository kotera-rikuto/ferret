// 退会（アカウント削除）の共有定義。
//
// 画面（app/settings/DeleteAccountForm.tsx）・API（app/api/account/delete/route.ts）・
// テストが同じ値を見るために、依存ゼロのここに置く（lib/feedback.ts と同じ役）。
//
// ⚠️ **消す範囲は法務文書が先に約束している。** 実装の都合で減らしてはいけない。
//   利用規約 第12条 / プライバシーポリシー 第7条:
//   「退会したときは、回答、採点結果、進行状況を含む利用者のデータを削除します」
// どちらも 2026-08-18（C2）に公開済みなので、ここを削ると
// **公開している文書に書いてあることが実行できない状態**になる。

/**
 * 退会の確認欄に入力させる語。
 *
 * オーナー判断（2026-08-19）: 文字の入力とパスワードの再入力を**両方**求める。
 * 文字入力は押し間違いを防ぎ、パスワードは離席した端末を触った他人を防ぐ。
 * 片方だけでは片方の事故しか防げない。
 */
export const DELETE_CONFIRM_WORD = "削除";

/**
 * 退会で消すテーブル。**子 → 親の順に並べてある。**
 *
 * この順でないと外部キーに引っかかって削除が途中で止まる。
 * `problem_feedback` は `user_attempts` を参照している（`attempt_id`）ため、
 * 回答ログより先に消すこと。
 *
 * 定数にしているのは、順番そのものが仕様だから。テストも同じ配列を見るので、
 * 実装側のループを書き換えて順番が入れ替われば結合テストが落ちる。
 *
 * ⚠️ **`subscriptions` の行を消すことは、Stripe の解約ではない。**
 * 決済（D2）を入れたら、**この行を消す前に Stripe 側のサブスクリプションを
 * 解約する処理**を足すこと。忘れると、退会したのに課金だけ続く。
 * いまは Stripe 未実装で行が1件も無いため、削除だけ先に用意してある。
 */
export const DELETE_TARGETS = [
  { table: "problem_feedback", column: "user_id" },
  { table: "user_attempts", column: "user_id" },
  { table: "subscriptions", column: "user_id" },
  { table: "users", column: "id" },
] as const;
