/** LP（トップページ）に出す件数。全件は `/changelog` にある */
export const CHANGELOG_ON_LP = 3;

/** LP に出す最新ぶん。**残りがあるかどうかも呼び出し側が知りたい**ので件数は別に持たせない */
export function latestChangelog(
  count: number = CHANGELOG_ON_LP,
): readonly ChangelogEntry[] {
  return CHANGELOG.slice(0, count);
}

/**
 * `2026-08-25` → `2026年8月25日`。
 *
 * `Intl` や `Date` を使わない。**`new Date("2026-08-25")` は UTC の0時**として読まれるので、
 * 日本時間で整形すると同じ日に戻るとは限らない（表示が1日ずれる）。
 * ここで扱うのは時刻を持たない「日付」なので、文字として切って組み直すのが正しい。
 */
export function formatChangelogDate(date: string): string {
  const [y, m, d] = date.split("-");
  return `${y}年${Number(m)}月${Number(d)}日`;
}
