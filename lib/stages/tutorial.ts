// 最初の数問（肩慣らし）の範囲。**判定の出どころはここ1か所**（E15・2026-09-12）。
//
// A3（2026-08-26）でステージ1〜3を「引っかけの無い問題」に差し替えたが、
// **画面には何の印も出していなかった**ので、経験者からは
// 「簡単な問題が並んでいる」だけに見えていた。印を出すための範囲がこれ。
//
// **`problems` に欄を足さなかった**（オーナー判断 2026-09-12・案A）。
// 章（`lib/stages/chapters.ts`）と同じで、範囲は `order` で機械的に決まり、
// 差し替えた側（A3）で確定している。カラムにすると101行ぶんの入力と
// その検証が増えるのに、決まり方は変わらない。
// 章を跨いで問題を差し替える運用が始まったら、章と一緒にカラム化を検討する。
//
// ⚠️ **画面に `order <= 3` と直接書かないこと。** `lib/progress/preview.ts` と同じ理由で、
// 2か所に書くと片方だけ直したときに**印の範囲と実際に素直な問題の範囲がズレる** ──
// しかもズレた側には何の症状も出ない（印が1つ多いだけの画面は正常に見える）。

/**
 * 肩慣らしとして印を出すステージ番号（`problems.order`）の上限。**両端を含む。**
 *
 * **3 は A3 で実際に差し替えた問数と同じ。**（差し替え後の難度は 1 → 2 → 2）
 * 4・5問目は A3 で触っていないので含めない ── 印の範囲を実態より広げると、
 * 「肩慣らしのはずの問題で引っかかる」という体験を作ることになる。
 *
 * ⚠️ **`id` ではなく `order` で区切る。** 実データの `id` は `order` と一致していない
 * （ステージ1の id は 8）。`id` で書くと、問題を入れ直した日に別の問題へ印が移る。
 */
export const TUTORIAL_MAX_ORDER = 3;

/** そのステージ番号が肩慣らしの範囲か */
export function isTutorialOrder(order: number | null | undefined): boolean {
  return (
    typeof order === "number" &&
    Number.isInteger(order) &&
    order >= 1 &&
    order <= TUTORIAL_MAX_ORDER
  );
}
