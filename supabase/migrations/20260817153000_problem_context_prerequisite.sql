-- problems に「実行結果」と「前提知識」の欄を足す
-- 作成: 2026-08-17 / 出典: tasks/E4-問題データに欄を足す.md
--
-- どちらも一部の問題にだけ入る欄なので NULL 許容にする。
-- 既存の問題が入っているため NOT NULL にできないという事情もあるが、
-- それ以前に「全問に必ず書く」性質の情報ではない。空なら画面に出さないだけ。
--
-- 2欄を1本にまとめているのは、適用が1回で済むこと以上に、
-- 同時期に走る他タスクのマイグレーションと適用順が絡まないようにするため。

begin;

-- 実行結果。
--
-- 影響型（スタックトレースや落ちたテストの出力から原因の場所を特定する読み方）で使う。
-- コード欄に押し込むとエラー文がコードの一部として表示され、本物の画面と
-- 見え方が変わってしまう（design/移植残タスク.md §6）。
--
-- 区切り記号（例 `---実行結果---`）を code 本文に書く案は採らなかった。
-- 書き忘れると壊れるうえ、壊れたことに気づく仕組みを別に用意しなければならない。
-- 100問を1問ずつ手で作る段階では、混ざりようのない別の欄にするほうが安い。
alter table public.problems
  add column context text;

comment on column public.problems.context is
  '実行結果（エラーログ・スタックトレース・テスト出力など）。コードとは別のパネルに表示する。影響型など必要な問題だけ入れ、NULL なら表示しない';

-- 前提知識。
--
-- 分からない語が1つあるだけで手が止まり、検索で外のサイトへ出ていって戻ってこない。
-- それを埋めるための最小限の説明で、教科書の代わりではない
-- （Ferret の価値は知識の提供ではなく他人のコードを読む訓練）。
--
-- 400字の上限は「数行に留める」という位置づけを機械側で守るためのもの。
-- ガイドの注意書きだけでは、100問を作るあいだに必ず伸びていく。
alter table public.problems
  add column prerequisite text check (char_length(prerequisite) <= 400);

comment on column public.problems.prerequisite is
  '前提知識。数行の短い説明（400字以内）。問題画面で開いて読む表示専用の欄で、採点プロンプトには渡さない。答えそのものを書かないこと';

commit;
