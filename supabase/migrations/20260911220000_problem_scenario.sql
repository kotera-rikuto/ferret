-- problems に「場面」の欄を足す
-- 作成: 2026-09-11 / 出典: tasks/A4-問題に実務の文脈を足す.md
--
-- 設問がいきなりコードの話から始まっており、「なぜこのコードを読んでいるのか」が
-- どこにも書かれていない。実務でコードを読むときは必ず理由があって
-- （引き継いだ・レビューを頼まれた・相談された）、その理由が読み方を決める。
-- いまの形は問題集に近く、Ferret が売りにしている「他人のコードが読める」とは
-- 別の作業になっている。
--
-- **既存の context を使い回さなかった理由:** context は影響型の「実行結果」で
-- 既に4問が使っている。同じ欄に性質の違う文章を混ぜると、画面側は
-- 「コードの枠か、場面の枠か」を内容から推測するしかなくなる。

begin;

-- 場面。
--
-- 問題を開いた直後に、暗い背景の上のカードとして1回だけ出す
-- （app/problems/[id]/ScenarioIntro.tsx）。閉じるとその回は消える。
--
-- **表示専用。採点プロンプトには渡さない**（prerequisite と同じ扱い）。
-- 渡すと場面の文章に引っ張られて点が動く。app/api/score/route.ts は
-- 列を名指しで select しているので、ここに足しただけでは渡らない。
--
-- 120字の上限は「2〜3行に留める」を機械側で守るためのもの。
-- 本題はコードを読むことで、場面はその入口でしかない。
-- prerequisite の 400字より短いのは、こちらが**閉じる前に必ず目に入る**
-- 全画面のカードだから ── 長いと、コードに辿り着く前に読むのをやめる。
alter table public.problems
  add column scenario text check (char_length(scenario) <= 120);

comment on column public.problems.scenario is
  '場面（どういう状況でこのコードを読むことになったか）。2〜3行・120字以内。問題を開いた直後にカードで1回だけ表示する表示専用の欄で、採点プロンプトには渡さない。答えや結論を書かないこと';

commit;
